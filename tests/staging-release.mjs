import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {spawnSync} from 'node:child_process';
import {writeManifest,verifyManifest} from '../tools/backup-manifest.mjs';
const root=path.resolve(import.meta.dirname,'..');
const build=env=>spawnSync(process.execPath,['tools/build-staging.mjs'],{cwd:root,env:{...process.env,LX_STAGING_SUPABASE_URL:'',LX_STAGING_PUBLISHABLE_KEY:'',...env},encoding:'utf8'});
assert.notEqual(build({LX_STAGING_SUPABASE_URL:'https://ubidogquzpdvrbzbhxda.supabase.co',LX_STAGING_PUBLISHABLE_KEY:'sb_publishable_fake'}).status,0,'Production project cannot be configured as staging');
assert.notEqual(build({LX_STAGING_SUPABASE_URL:'http://insecure.supabase.co',LX_STAGING_PUBLISHABLE_KEY:'sb_publishable_fake'}).status,0);
const roleToken=Buffer.from(JSON.stringify({role:'service_role'})).toString('base64url');
assert.notEqual(build({LX_STAGING_SUPABASE_URL:'https://isolated.supabase.co',LX_STAGING_PUBLISHABLE_KEY:'eyJ.'+roleToken+'.signature'}).status,0,'Service keys cannot enter the public build');
const result=build({});assert.equal(result.status,0,result.stderr);
const output=path.join(root,'build/staging');
const code=await fs.readFile(path.join(output,'lxplus.bundle.js'),'utf8');
const config=vm.runInNewContext('('+code.match(/LX\.config=([\s\S]*?);\n/)[1]+')');
assert.equal(config.environment,'isolated-staging');assert.equal(config.supabase.publishableKey,'');
assert.equal(config.supabase.url,'https://staging-not-configured.invalid');
for(const file of ['.git','backend','supabase/migrations','tools','tests','.env'])await assert.rejects(fs.access(path.join(output,file)));
for(const file of ['index.html','lxplus.bundle.js','lxplus.next.css','lxplus.next-console.js','js/account-policy.js','service-worker.js'])await fs.access(path.join(output,file));
const dir=path.join(root,'build/backup-test');await fs.rm(dir,{recursive:true,force:true});await fs.mkdir(dir,{recursive:true});
await fs.writeFile(path.join(dir,'sample.sql'),'-- synthetic backup fixture');
const manifest=await writeManifest(dir);assert.equal(manifest.restore_verified,false);assert.equal(manifest.cleanup_allowed,false);
assert.equal((await verifyManifest(dir)).integrity_verified,true);
await fs.writeFile(path.join(dir,'sample.sql'),'tampered');await assert.rejects(verifyManifest(dir),/do not match/);
await fs.writeFile(path.join(dir,'sample.sql'),'-- synthetic backup fixture');
await fs.writeFile(path.join(dir,'extra.sql'),'unexpected');await assert.rejects(verifyManifest(dir),/do not match/);
await fs.rm(path.join(dir,'extra.sql'));await fs.symlink('sample.sql',path.join(dir,'link.sql'));
await assert.rejects(verifyManifest(dir),/symbolic links/);await fs.rm(dir,{recursive:true});
console.log('PASS staging release: production isolation, public-key checks, private-file exclusions and backup tamper detection. Hash verification never authorizes account cleanup.');
