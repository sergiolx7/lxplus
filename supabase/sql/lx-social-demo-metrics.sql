-- LX Social: clearly-labeled, reversible interface test counters.
-- DO NOT insert manufactured lx_post_likes or lx_friendships: authentic
-- reactions, relationships, ranking and monetization remain unaffected.
create table if not exists public.lx_demo_social_metrics(
 target_kind text not null check(target_kind in ('post','profile')),
 target_id uuid not null,
 demo_count integer not null default 0 check(demo_count between 0 and 100000),
 updated_at timestamptz not null default now(),
 updated_by uuid references auth.users(id),
 primary key(target_kind,target_id)
);
create table if not exists public.lx_demo_social_audit(
 id bigint generated by default as identity primary key,
 target_kind text not null,
 target_id uuid not null,
 previous_count integer not null,
 new_count integer not null,
 updated_by uuid not null references auth.users(id),
 created_at timestamptz not null default now()
);
create index if not exists lx_demo_social_audit_target on public.lx_demo_social_audit(target_kind,target_id,created_at desc);
alter table public.lx_demo_social_metrics enable row level security;
alter table public.lx_demo_social_audit enable row level security;
revoke all on table public.lx_demo_social_metrics,public.lx_demo_social_audit from public,anon,authenticated;
grant select,insert,update,delete on public.lx_demo_social_metrics to service_role;
grant select,insert on public.lx_demo_social_audit to service_role;
revoke all on sequence public.lx_demo_social_audit_id_seq from public,anon,authenticated;
grant usage,select on sequence public.lx_demo_social_audit_id_seq to service_role;

create or replace function public.lx_demo_social_set(p_kind text,p_target uuid,p_count integer)
returns jsonb language plpgsql security definer set search_path='' as $$
declare previous_count int:=0; role_name text;
begin
 role_name:=public.lx_admin_role();
 if auth.uid() is null or role_name not in ('owner','administrator') then raise exception 'ADMIN_REQUIRED';end if;
 if p_kind not in ('post','profile') or p_target is null or p_count is null or p_count not between 0 and 100000 then raise exception 'INVALID_DEMO_METRIC';end if;
 if p_kind='post' and not exists (select 1 from public.lx_posts where id=p_target and status='published' and visibility='public') then raise exception 'PUBLIC_POST_REQUIRED';end if;
 if p_kind='profile' and not exists (select 1 from public.lx_profiles where user_id=p_target and social_visible=true and approved=true) then raise exception 'PUBLIC_PROFILE_REQUIRED';end if;
 perform pg_advisory_xact_lock(hashtextextended(p_kind||p_target::text,81));
 select demo_count into previous_count from public.lx_demo_social_metrics where target_kind=p_kind and target_id=p_target for update;
 previous_count:=coalesce(previous_count,0);
 insert into public.lx_demo_social_metrics(target_kind,target_id,demo_count,updated_at,updated_by)
 values(p_kind,p_target,p_count,now(),auth.uid())
 on conflict(target_kind,target_id) do update set demo_count=excluded.demo_count,updated_at=now(),updated_by=excluded.updated_by;
 if previous_count<>p_count then
  insert into public.lx_demo_social_audit(target_kind,target_id,previous_count,new_count,updated_by)
  values(p_kind,p_target,previous_count,p_count,auth.uid());
 end if;
 return jsonb_build_object('kind',p_kind,'target_id',p_target,'demo_count',p_count,'previous_count',previous_count,'changed',previous_count<>p_count);
end $$;
revoke all on function public.lx_demo_social_set(text,uuid,integer) from public,anon;
grant execute on function public.lx_demo_social_set(text,uuid,integer) to authenticated;

-- Only expose demo labels for public-visible entities, not arbitrary member IDs.
create or replace function public.lx_demo_social_visible(p_posts uuid[],p_profiles uuid[])
returns jsonb language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null then raise exception 'AUTH_REQUIRED';end if;
 if coalesce(cardinality(p_posts),0)>50 or coalesce(cardinality(p_profiles),0)>50 then raise exception 'TOO_MANY_METRICS';end if;
 return coalesce((select jsonb_agg(jsonb_build_object('kind',d.target_kind,'id',d.target_id,'demo_count',d.demo_count))
  from public.lx_demo_social_metrics d
  where d.demo_count>0 and (
   (d.target_kind='post' and d.target_id=any(coalesce(p_posts,'{}'::uuid[]))
    and exists(select 1 from public.lx_posts p where p.id=d.target_id and p.status='published' and p.visibility='public'))
   or
   (d.target_kind='profile' and d.target_id=any(coalesce(p_profiles,'{}'::uuid[]))
    and exists(select 1 from public.lx_profiles p where p.user_id=d.target_id and p.social_visible=true and p.approved=true))
  )
 ),'[]'::jsonb);
end $$;
revoke all on function public.lx_demo_social_visible(uuid[],uuid[]) from public,anon;
grant execute on function public.lx_demo_social_visible(uuid[],uuid[]) to authenticated;

create or replace function public.lx_demo_social_admin()
returns jsonb language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or public.lx_admin_role() not in ('owner','administrator') then raise exception 'ADMIN_REQUIRED';end if;
 return coalesce((select jsonb_agg(jsonb_build_object('kind',d.target_kind,'target_id',d.target_id,
  'demo_count',d.demo_count,'updated_at',d.updated_at,
  'label',case when d.target_kind='post' then left(coalesce((select p.body from public.lx_posts p where p.id=d.target_id),'Publicação removida'),90)
  else left(coalesce((select p.name from public.lx_profiles p where p.user_id=d.target_id),'Conta indisponível'),90) end)
  order by d.updated_at desc)
 from (select * from public.lx_demo_social_metrics order by updated_at desc limit 60) d),'[]'::jsonb);
end $$;
revoke all on function public.lx_demo_social_admin() from public,anon;
grant execute on function public.lx_demo_social_admin() to authenticated;
